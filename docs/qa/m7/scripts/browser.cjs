const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/local/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1365,height:960}});
 const errors=[]; const sockets=[];
 page.on('pageerror', e=>errors.push(e.message));
 page.on('websocket', ws=>sockets.push(ws.url()));
 await page.goto('http://127.0.0.1:15173/events');
 await page.getByRole('heading',{name:'События',exact:true}).waitFor();
 await page.locator('article[data-event-id]').first().waitFor();
 await page.getByText('Прямой эфир событий',{exact:true}).waitFor();
 const card=page.locator('article[data-event-id]').filter({has:page.getByRole('button',{name:'Подтвердить',exact:true})}).first();
 await card.waitFor(); const id=await card.getAttribute('data-event-id');
 await card.locator('textarea').fill('QA M7: оператор проверил зону');
 await card.getByRole('button',{name:'Подтвердить',exact:true}).click();
 await page.locator(`article[data-event-id="${id}"]`).getByText('Подтверждено',{exact:true}).waitFor();
 const saved=await (await page.request.get(`http://127.0.0.1:18000/api/v1/events/${id}`)).json();
 assert.equal(saved.status,'ACKNOWLEDGED'); assert(saved.acknowledged_at); assert.equal(saved.note,'QA M7: оператор проверил зону');
 const second=page.locator('article[data-event-id]').filter({has:page.getByRole('button',{name:'Ложная тревога',exact:true})}).first();
 const fpId=await second.getAttribute('data-event-id');
 await second.getByRole('button',{name:'Ложная тревога',exact:true}).click();
 await page.locator(`article[data-event-id="${fpId}"]`).getByText('Ложная тревога',{exact:true}).waitFor();
 const fp=await (await page.request.get(`http://127.0.0.1:18000/api/v1/events/${fpId}`)).json(); assert(fp.false_positive_at);
 const selects=page.locator('select');await selects.nth(1).selectOption('ACKNOWLEDGED');
 await page.waitForTimeout(600);assert(await page.locator('article[data-event-id]').count()>0);
 assert.equal(await page.getByRole('button',{name:'Подтвердить',exact:true}).count(),0);
 await selects.nth(1).selectOption('');await page.waitForTimeout(500);
 fs.mkdirSync('/data/work-m7/Ai-Detector/docs/qa/m7',{recursive:true});
 await page.screenshot({path:'/data/work-m7/Ai-Detector/docs/qa/m7/events-light.png',fullPage:false});
 const cameras=await (await page.request.get('http://127.0.0.1:18000/api/v1/cameras')).json();const camera=cameras.find(c=>c.enabled);
 await page.goto(`http://127.0.0.1:15173/monitoring/${camera.id}`);
 await page.getByRole('heading',{name:'Телеметрия',exact:true}).waitFor();
 await page.waitForFunction(()=>document.body.innerText.includes('Inference:'));
 assert(sockets.some(s=>s.includes('/telemetry'))); assert(sockets.some(s=>s.includes('/preview')));
 await page.screenshot({path:'/data/work-m7/Ai-Detector/docs/qa/m7/telemetry-light.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:15173/events');await page.locator('article[data-event-id]').first().waitFor();await page.waitForTimeout(400);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:'/data/work-m7/Ai-Detector/docs/qa/m7/events-mobile.png',fullPage:false});
 await page.evaluate(()=>{document.documentElement.classList.add('dark');});
 await page.screenshot({path:'/data/work-m7/Ai-Detector/docs/qa/m7/events-mobile-dark.png',fullPage:false});
 assert.deepEqual(errors,[]); console.log(JSON.stringify({ack:id,false_positive:fpId,websockets:sockets,pageerrors:errors,mobileOverflow:false}));
 await browser.close();process.exit(0);
})().catch(e=>{console.error(e);process.exit(1)});
